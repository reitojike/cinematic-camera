"""Public common R7 settings and synthetic all-pixel reference; never reads photos."""
from __future__ import annotations

import argparse
import gzip
from pathlib import Path

import numpy as np

import r6_diagnose as r
import r7_base as base
import r7_final as fin
import r7_look as k
import r7b_skin as sk
import r7c_punch as cp

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "app/src/main/java/dev/cinematic/p0/gpu/constants/R7BaseV1.kt"
FIXTURE = ROOT / "app/src/test/resources/r7_base_v1.csv.gz"
# Provisional pure float32 boundary, chosen before comparisons. No real-DNG quality claim.
ATOL = 2e-5


def constants():
    foundation = base.FOUNDATION
    assert foundation["rgb"] == [1., 1., 1.]
    values = {"FOUNDATION_EV": foundation["ev"], "CONTRAST": foundation["contrast"],
              "SATURATION": foundation["saturation"], "SKIN_SATURATION": foundation["skin_saturation"],
              "YELLOW_RED": foundation["yellow_rgb"][0], "YELLOW_GREEN": foundation["yellow_rgb"][1],
              "YELLOW_BLUE": foundation["yellow_rgb"][2], "PROFILE_SHIFT": k.PROFILE_LEVELS["P2"],
              "HIGHLIGHTS": k.IMMERSION_LEVELS["I1"]["highlights"],
              "SHADOWS": k.IMMERSION_LEVELS["I1"]["shadows"], "VIBRANCE": k.IMMERSION_LEVELS["I1"]["vibrance"],
              "BRIGHTNESS_EV": sk.BRIGHTNESS_LEVELS["E2"], "BLACK": cp.CRISP_LEVELS["K1"]["black"],
              "CRISP_CONTRAST": cp.CRISP_LEVELS["K1"]["contrast"], "CRISP_CHROMA": cp.CRISP_LEVELS["K1"]["chroma"]}
    return "\n".join(["// Generated by tools/raw_baseline/export_android_r7.py --write. Do not edit.",
                      "package dev.cinematic.p0.gpu.constants", "", "internal object R7BaseV1 {"] +
                     [f"    const val {key} = {float(value):.10g}" + (".0" if float(value).is_integer() else "")
                      for key, value in values.items()] + ["}", ""])


def scenes():
    rng = np.random.default_rng(78)
    for name, w, h, ev, ellipses in [
            ("single", 1, 1, 0., []), ("narrow", 1, 37, -.7, [[.5, .6, .8, .3]]),
            ("wide", 39, 1, .8, []), ("tiny", 7, 5, 0., [[.5, .6, .3, .4]]),
            ("stage", 64, 48, -.4, [[.3, .6, .12, .3], [.7, .4, .15, .25]]),
            ("zero-roi", 33, 25, .5, []), ("neutral", 31, 29, 0., [])]:
        image = rng.uniform(.003, .7, (h, w, 3)).astype(np.float32)
        if name == "neutral":
            image[:] = np.linspace(.001, 1, h * w).reshape(h, w, 1)
        elif name != "single":
            image.reshape(-1, 3)[:5] = [[1.3, -.04, .15], [.01, .005, .4], [.62, .42, .32],
                                      [1., 1., 1.], [0., 0., 0.]]
        yield name, image, ev, ellipses


def fixture():
    lines = ["# synthetic R7 boundary B only; no decode/WB/gamut/face detection/photo data",
             "# CASE,name,width,height,externalEV; PIX,inputRGB,ROI,logBase,profileRGB,toneRGB,foundationRGB,vibranceRGB,crispRGB,outputRGB"]
    for name, image, ev, ellipses in scenes():
        h, w = image.shape[:2]
        roi = r.skin_mask(w, h, ellipses)
        stages = base.stages(image, roi, ev)
        # Independent existing entry point, with no per-scene exceptions.
        choice = {key: value for key, value in fin.RECIPE.items() if key != "per_scene"}
        oracle = fin.render(image, {"base_ev": ev, "skin": ellipses}, base.FOUNDATION, choice)
        np.testing.assert_array_equal(stages[-1], oracle)
        log_base = k.smooth_log_luma(np.maximum(stages[0] @ r.LUMA, 1e-5))
        rows = np.concatenate((image, roi[..., None], log_base[..., None], *stages), axis=-1).reshape(-1, 23)
        lines.append(f"CASE,{name},{w},{h},{ev:.17g}")
        lines.extend("PIX," + ",".join(f"{float(value):.10g}" for value in row) for row in rows)
    return "\n".join(lines) + "\n"


def check_exports():
    if CONSTANTS.read_text(encoding="utf-8") != constants():
        raise AssertionError("R7 constants differ from public common recipe")
    actual = gzip.decompress(FIXTURE.read_bytes()).decode().splitlines()
    expected = fixture().splitlines()
    if len(actual) != len(expected):
        raise AssertionError("R7 fixture layout changed")
    maximum = 0.
    for line, (got, want) in enumerate(zip(actual, expected), 1):
        if want.startswith("PIX,"):
            a = np.array(got.split(",")[1:], dtype=float)
            b = np.array(want.split(",")[1:], dtype=float)
            np.testing.assert_allclose(a, b, atol=ATOL, rtol=0, equal_nan=False, err_msg=f"R7 line {line}")
            maximum = max(maximum, float(np.max(np.abs(a - b))))
        elif got != want:
            raise AssertionError(f"R7 metadata differs at line {line}")
    print(f"R7 regeneration maximum absolute error={maximum:.10g}; provisional tolerance={ATOL}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        CONSTANTS.write_text(constants(), encoding="utf-8", newline="\n")
        FIXTURE.write_bytes(gzip.compress(fixture().encode(), mtime=0))
    else:
        check_exports()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
