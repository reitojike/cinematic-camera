"""Synthetic stage-3 regression reference; lossless gzip keeps every test pixel."""
from __future__ import annotations

import argparse
import ast
import gzip
from pathlib import Path

import numpy as np

from export_android_mist import function, scenes
import r10_iconic as ic
import r10e_portrait as pe
import r10h_refine as h
import stage_clear as sc

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "app/src/main/java/dev/cinematic/p0/gpu/constants/StageClearOrtonV1.kt"
FIXTURE = ROOT / "app/src/test/resources/stage_clear_orton_v1.csv.gz"


def constants() -> str:
    calls = [n for n in ast.walk(function(h, "orton")) if isinstance(n, ast.Call)]
    blur = next(n for n in calls if isinstance(n.func, ast.Attribute) and n.func.attr == "blur_rgb")
    transfer = next(n for n in calls if isinstance(n.func, ast.Attribute) and n.func.attr == "unit_to_linear")
    floor = next(n for n in calls if isinstance(n.func, ast.Attribute) and n.func.attr == "maximum"
                 and isinstance(n.args[1], ast.Constant))
    lo, hi = h.ORTON_HIGHLIGHT
    scalars = {"RADIUS": ast.literal_eval(blur.args[1]),
               "AMOUNT": ast.literal_eval(transfer.args[0].right.left.left),
               "HIGHLIGHT_START": lo, "HIGHLIGHT_SPAN": hi - lo,
               "CHROMA_FLOOR": ast.literal_eval(floor.args[1])}
    lines = ["// Generated by tools/raw_baseline/export_android_orton.py --write. Do not edit.",
             "package dev.cinematic.p0.gpu.constants", "", "internal object StageClearOrtonV1 {"]
    return "\n".join(lines + [f"    const val {key} = {value:.10g}" for key, value in scalars.items()] + ["}", ""])


def fixture() -> str:
    lines = ["# synthetic stage-3 regression only; linear sRGB/D65; no photo data",
             "# CASE,name,width,height,strength,lightAmount; PIX,baseRGB,skin,mistedRGB,ortonRGB,resultRGB"]
    for name, base in scenes():
        skin = sc.skin_weight(base)
        for strength in sc.STRENGTHS:
            glowed = ic.glow(base, sc.scaled_glow(strength)) if strength > 0 else base
            amount = h.auto_strength(glowed) * strength
            misted = glowed + amount * (pe.black_mist(glowed, skin) - glowed)
            orton = h.orton(misted, skin)
            output = misted + amount * (orton - misted)
            lines.append(f"CASE,{name},{base.shape[1]},{base.shape[0]},{strength:.17g},{amount:.17g}")
            rows = np.concatenate((base, skin[..., None], misted, orton, output), axis=-1).reshape(-1, 13)
            lines += ["PIX," + ",".join(f"{float(v):.10g}" for v in row) for row in rows]
    return "\n".join(lines) + "\n"


def assert_regenerated_pixels(actual, expected, label, atol=2e-5):
    """Compare all scalars to the fixed golden; default is the existing SC-010 boundary."""
    actual, expected = np.asarray(actual, dtype=float), np.asarray(expected, dtype=float)
    if actual.shape != expected.shape:
        raise AssertionError(f"{label}: shape differs")
    if not np.all(np.isfinite(actual) & np.isfinite(expected)):
        raise AssertionError(f"{label}: nonfinite pixels")
    np.testing.assert_allclose(actual, expected, atol=atol, rtol=0, equal_nan=False, err_msg=label)


def check_exports() -> None:
    if CONSTANTS.read_text(encoding="utf-8") != constants():
        raise AssertionError("Generated Orton constants differ from PC")
    expected = fixture().splitlines()
    actual = gzip.decompress(FIXTURE.read_bytes()).decode("utf-8").splitlines()
    if len(expected) != len(actual):
        raise AssertionError("Orton fixture shape changed")
    # Diagnose cross-runner float32 drift over ALL pixels before the first assertion.
    want_pixels = np.array([row.split(",")[1:] for row in expected if row.startswith("PIX,")], dtype=float)
    got_pixels = np.array([row.split(",")[1:] for row in actual if row.startswith("PIX,")], dtype=float)
    if want_pixels.shape == got_pixels.shape:
        errors = np.abs(got_pixels - want_pixels)
        worst = np.unravel_index(np.argmax(errors), errors.shape)
        print(f"Orton regeneration max_abs={errors[worst]:.10g}; over_2e-6={np.count_nonzero(errors > 2e-6)}; "
              f"worst_pixel/channel={worst}; expected={want_pixels[worst]:.10g}; got={got_pixels[worst]:.10g}")
    for line, (want, got) in enumerate(zip(expected, actual), 1):
        a, b = want.split(","), got.split(",")
        if a[0] == "PIX":
            if a[0] != b[0] or len(a) != len(b):
                raise AssertionError(f"Orton fixture layout differs at line {line}")
            # Base/skin and stage-2 inputs retain their stricter, separately tested boundary.
            assert_regenerated_pixels(b[1:8], a[1:8], f"Orton inputs line {line}", atol=2e-6)
            assert_regenerated_pixels(b[8:], a[8:], f"Orton outputs line {line}")
        elif want != got:
            raise AssertionError(f"Orton fixture metadata differs at line {line}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        CONSTANTS.write_text(constants(), encoding="utf-8", newline="\n")
        raw = fixture().encode("utf-8")
        packed = gzip.compress(raw, mtime=0)
        assert gzip.decompress(packed) == raw
        FIXTURE.write_bytes(packed)
        print(f"Wrote synthetic Orton exports: {len(raw)} -> {len(packed)} bytes, lossless")
    else:
        check_exports()
        print("Orton exports match PC")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
