"""Stage-1 glow/skin-weight conformance from synthetic linear sRGB, no photos or I/O settings."""
from __future__ import annotations

import argparse
import ast
from pathlib import Path

import numpy as np

import r6_diagnose as r
import r7b_skin as sk
import r10_iconic as ic
import stage_clear as sc
from test_stage_clear import scene

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "app/src/main/java/dev/cinematic/p0/raw/StageClearGlowV1.kt"
FIXTURE = ROOT / "app/src/test/resources/stage_clear_glow_v1.csv"


def constants() -> str:
    # Pull the local algorithm constants from the reference, rather than hand-maintaining a copy.
    tree = ast.parse(Path(ic.__file__).read_text(encoding="utf-8"))
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "glow")

    def assignment(name):
        return next(n.value for n in ast.walk(fn) if isinstance(n, ast.Assign)
                    and any(isinstance(t, ast.Name) and t.id == name for t in n.targets))

    def radius(name, call_name):
        call = next(n for n in ast.walk(assignment(name)) if isinstance(n, ast.Call)
                    and isinstance(n.func, ast.Name) and n.func.id == call_name)
        return ast.literal_eval(call.args[1])

    kernels = ast.literal_eval(assignment("bloom").args[0].generators[0].iter)
    protect = ast.literal_eval(assignment("protect").right.left)
    scalars = {"THRESHOLD": sc.GLOW["threshold"], "BLOOM": sc.GLOW["bloom"],
               "HALATION": sc.GLOW["halation"], "DIFFUSION": sc.GLOW["diffusion"],
               "HALATION_RADIUS": radius("halation", "blur"),
               "SKIN_RADIUS": radius("protect", "blur"), "SKIN_PROTECT": protect,
               "DIFFUSION_RADIUS": radius("soft", "blur_rgb")}
    lines = ["// Generated by tools/raw_baseline/export_android_glow.py --write. Do not edit.",
             "package dev.cinematic.p0.raw", "", "internal object StageClearGlowV1 {"]
    lines += [f"    const val {name} = {value:.10g}" for name, value in scalars.items()]
    lines.append("    val BLOOM_KERNELS: Array<Pair<Double, Float>> get() = arrayOf(")
    lines += [f"        {radius:.10g} to {weight:.10g}f," for radius, weight in kernels]
    lines += ["    )", "    val HALATION_TINT: FloatArray get() = floatArrayOf(",
              "        " + ", ".join(f"{float(v):.10g}f" if float(v) != 1 else "1f"
                                      for v in ic.HALATION_TINT) + ",", "    )", "}", ""]
    return "\n".join(lines)


def cases():
    image, _, _ = scene()
    yield "original-synthetic-stage", image
    yy, xx = np.mgrid[:7, :191].astype(np.float32)
    wide = np.stack((.01 + (xx % 23) * .08, .02 + (yy + xx % 11) * .06,
                     .03 + (xx % 19) * .1), -1)
    wide[:, 80:100] = (.62, .30, .22)
    yield "wide-colour-and-skin", wide
    yield "tall-colour-and-skin", wide.transpose(1, 0, 2).copy()
    yield "dark-flat", np.full((7, 9, 3), .01, dtype=np.float32)
    yield "black", np.zeros((2, 3, 3), dtype=np.float32)
    levels = np.array([0, .69999, .7, .70001, .8, 1., 1.3, 2.], dtype=np.float32)
    yield "threshold-and-over-white", np.tile(levels[None, :, None], (3, 1, 3))
    colours = np.array([[-.2, .08, 1.4], [-.2, -.1, -.05], [.62, .30, .22], [.8, .16, .25],
                        [2., .02, .01], [.01, .02, 2.], [1.3, 1.3, 1.3], [0., 0., 0.],
                        [.15, .15, .15], [1., .3, .2]], dtype=np.float32)
    yield "signed-and-skin-swatches", np.tile(colours, (4, 1, 1))
    impulse = np.zeros((5, 191, 3), dtype=np.float32)
    impulse[0, 0] = (4, 4, 4)
    yield "edge-white-light", impulse
    yield "single-skin-pixel", np.array([[[.62, .3, .22]]], dtype=np.float32)


def fixture() -> str:
    lines = ["# synthetic stage-1 only; RGB linear sRGB/D65; no photo data",
             "# CASE,name,width,height; PIX,inputRGB,rawSkin,blurredSkin,glowHalfRGB,glowOneRGB"]
    for name, base in cases():
        skin = sk.skin_weight(r.oklab(base))
        smooth = sc.skin_weight(base)
        half = ic.glow(base, sc.scaled_glow(.5))
        one = ic.glow(base, sc.scaled_glow(1.))
        lines.append(f"CASE,{name},{base.shape[1]},{base.shape[0]}")
        rows = np.concatenate((base, skin[..., None], smooth[..., None], half, one), axis=-1).reshape(-1, 11)
        lines += ["PIX," + ",".join(f"{float(v):.10g}" for v in row) for row in rows]
    return "\n".join(lines) + "\n"


def check_exports() -> None:
    if CONSTANTS.read_text(encoding="utf-8") != constants():
        raise AssertionError("Generated glow constants differ from PC")
    expected, committed = fixture().splitlines(), FIXTURE.read_text(encoding="utf-8").splitlines()
    if len(expected) != len(committed):
        raise AssertionError("Glow fixture shape changed")
    for line, (want, got) in enumerate(zip(expected, committed), 1):
        a, b = want.split(","), got.split(",")
        if a[0] == "PIX":
            if a[0] != b[0] or len(a) != len(b):
                raise AssertionError(f"Glow fixture layout differs at line {line}")
            np.testing.assert_allclose(np.array(b[1:], dtype=float), np.array(a[1:], dtype=float),
                                       atol=2e-6, rtol=0, err_msg=f"glow fixture line {line}")
        elif want != got:
            raise AssertionError(f"Glow fixture metadata differs at line {line}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        CONSTANTS.write_text(constants(), encoding="utf-8", newline="\n")
        FIXTURE.write_text(fixture(), encoding="utf-8", newline="\n")
    else:
        check_exports()
    print("Wrote synthetic glow exports" if args.write else "Glow exports match PC")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
