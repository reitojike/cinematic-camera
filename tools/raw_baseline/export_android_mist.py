"""Stage-2 black-mist conformance, including PC stage-1 -> stage-2 synthetic composition."""
from __future__ import annotations

import argparse
import ast
from pathlib import Path

import numpy as np

import r10_iconic as ic
import r10e_portrait as pe
import r10h_refine as h
import stage_clear as sc
from test_stage_clear import scene

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "app/src/main/java/dev/cinematic/p0/raw/StageClearMistV1.kt"
FIXTURE = ROOT / "app/src/test/resources/stage_clear_mist_v1.csv"


def function(module, name):
    tree = ast.parse(Path(module.__file__).read_text(encoding="utf-8"))
    return next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == name)


def constants() -> str:
    fn = function(pe, "black_mist")

    def assignment(name):
        return next(n.value for n in fn.body if isinstance(n, ast.Assign)
                    and any(isinstance(t, ast.Name) and t.id == name for t in n.targets))

    weight = assignment("weight")
    ramp = weight.left.args[0]
    halo = assignment("halo")
    result = next(n.value for n in fn.body if isinstance(n, ast.Return))
    auto = next(n.value for n in function(h, "auto_strength").body if isinstance(n, ast.Return))
    auto_clip = next(n for n in ast.walk(auto) if isinstance(n, ast.Call)
                     and isinstance(n.func, ast.Attribute) and n.func.attr == "clip")
    scalars = {
        "SOURCE_START": ast.literal_eval(ramp.left.right),
        "SOURCE_SPAN": ast.literal_eval(ramp.right),
        "SOURCE_POWER": ast.literal_eval(weight.right),
        "MIST_AMOUNT": ast.literal_eval(result.right.left.left),
        "SKIN_PROTECT": ast.literal_eval(assignment("protect").right.left),
        "NEAR_WHITE": h.NEAR_WHITE,
        "AUTO_START": ast.literal_eval(auto_clip.args[0].left.right),
        "AUTO_SPAN": ast.literal_eval(auto_clip.args[0].right),
        "AUTO_REDUCTION": ast.literal_eval(auto.right.left),
    }
    kernels = [(ast.literal_eval(term.right.args[1]), ast.literal_eval(term.left))
               for term in (halo.left, halo.right)]
    lines = ["// Generated by tools/raw_baseline/export_android_mist.py --write. Do not edit.",
             "package dev.cinematic.p0.raw", "", "internal object StageClearMistV1 {"]
    lines += [f"    const val {name} = {value:.10g}" for name, value in scalars.items()]
    lines.append("    val KERNELS: Array<Pair<Double, Float>> get() = arrayOf(")
    lines += [f"        {radius:.10g} to {weight:.10g}f," for radius, weight in kernels]
    return "\n".join(lines + ["    )", "}", ""])


def scenes():
    base, _, _ = scene()
    yield "synthetic-stage", base[::3, ::3].copy()
    yy, xx = np.mgrid[:5, :191].astype(np.float32)
    wide = np.stack((.01 + (xx % 23) * .08, .02 + (yy + xx % 11) * .06,
                     .03 + (xx % 19) * .1), -1)
    wide[:, 80:100] = (.62, .30, .22)
    yield "wide-skin-and-colour", wide
    yield "tall-skin-and-colour", wide.transpose(1, 0, 2).copy()
    yield "dark-flat", np.full((7, 9, 3), .1, dtype=np.float32)
    yield "single-signed-pixel", np.array([[[-.2, .08, 1.4]]], dtype=np.float32)
    signed = np.array([[-.2, 1.4, .08], [1.4, -.1, .08], [1.2, .2, -.2]], dtype=np.float32)
    yield "signed-source-positive-luma", np.tile(signed, (2, 1, 1))
    for count in (0, 2, 4, 7, 8):
        base = np.full((10, 20, 3), .2, dtype=np.float32)
        base.reshape(-1, 3)[:count] = 1.2
        yield f"white-count-{count}", base


def fixture() -> str:
    lines = ["# synthetic stage-2 only; base/glowed RGB linear sRGB/D65; no photo data",
             "# CASE,name,width,height,strength,whiteFraction,auto,lightAmount; PIX,baseRGB,skin,glowedRGB,mistRGB,resultRGB"]
    for name, base in scenes():
        skin = sc.skin_weight(base)
        for strength in sc.STRENGTHS:
            glowed = ic.glow(base, sc.scaled_glow(strength)) if strength > 0 else base
            mist = pe.black_mist(glowed, skin)
            fraction, auto = h.near_white_fraction(glowed), h.auto_strength(glowed)
            amount = auto * strength
            output = glowed + amount * (mist - glowed)
            lines.append(f"CASE,{name},{base.shape[1]},{base.shape[0]},{strength:.17g},{fraction:.17g},{auto:.17g},{amount:.17g}")
            rows = np.concatenate((base, skin[..., None], glowed, mist, output), axis=-1).reshape(-1, 13)
            lines += ["PIX," + ",".join(f"{float(v):.10g}" for v in row) for row in rows]
    return "\n".join(lines) + "\n"


def check_exports() -> None:
    if CONSTANTS.read_text(encoding="utf-8") != constants():
        raise AssertionError("Generated mist constants differ from PC")
    expected, actual = fixture().splitlines(), FIXTURE.read_text(encoding="utf-8").splitlines()
    if len(expected) != len(actual):
        raise AssertionError("Mist fixture shape changed")
    for line, (want, got) in enumerate(zip(expected, actual), 1):
        a, b = want.split(","), got.split(",")
        if a[0] == "PIX":
            if a[0] != b[0] or len(a) != len(b):
                raise AssertionError(f"Mist fixture layout differs at line {line}")
            np.testing.assert_allclose(np.array(b[1:], dtype=float), np.array(a[1:], dtype=float),
                                       atol=2e-6, rtol=0, err_msg=f"mist fixture line {line}")
        elif want != got:
            raise AssertionError(f"Mist fixture metadata differs at line {line}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        CONSTANTS.write_text(constants(), encoding="utf-8", newline="\n")
        FIXTURE.write_text(fixture(), encoding="utf-8", newline="\n")
    else:
        check_exports()
    print("Wrote synthetic mist exports" if args.write else "Mist exports match PC")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
