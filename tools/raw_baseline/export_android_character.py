"""Synthetic stages 4/5 and complete look from R7 base; never a DNG-path proof."""
from __future__ import annotations

import argparse
import gzip
from pathlib import Path

import numpy as np

from export_android_mist import scenes
from export_android_protections import cases as protection_cases
from test_stage_clear import scene
import r7_look as k
import r10_iconic as ic
import r10e_portrait as pe
import r10h_refine as h
import stage_clear as sc

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "app/src/main/java/dev/cinematic/p0/raw/StageClearCharacterV1.kt"
FIXTURE = ROOT / "app/src/test/resources/stage_clear_character_v1.csv.gz"


def constants() -> str:
    return ("// Generated by tools/raw_baseline/export_android_character.py --write. Do not edit.\n"
            "package dev.cinematic.p0.raw\n\ninternal object StageClearCharacterV1 {\n"
            f"    const val VIGNETTE = {sc.VIGNETTE:.10g}\n"
            f"    const val VIBRANCE = {sc.VIBRANCE:.10g}\n" + "}\n")


def cases():
    _, original_faces, _ = scene()
    for name, base in scenes():
        faces = original_faces[::3, ::3].copy() if name == "synthetic-stage" else np.zeros(base.shape[:2], np.float32)
        yield name, base, faces
    for name, base, faces in protection_cases():
        if name in ("face-49", "face-50", "soft-face", "mask-at-half"):
            yield name, base, faces


def fixture() -> str:
    lines = ["# synthetic R7-base look regression; linear sRGB/D65; no DNG/photo data",
             "# CASE,name,width,height,strength,faceFactor; PIX,baseRGB,face,stage3RGB,vignetteRGB,characterRGB,fullRGB"]
    for name, base, faces in cases():
        skin = sc.skin_weight(base)
        for strength in sc.STRENGTHS:
            glowed = ic.glow(base, sc.scaled_glow(strength)) if strength > 0 else base
            amount = h.auto_strength(glowed) * strength
            misted = glowed + amount * (pe.black_mist(glowed, skin) - glowed)
            stage3 = misted + amount * (h.orton(misted, skin) - misted)
            vignette = pe.vignette(stage3, sc.VIGNETTE * strength)
            character = k.vibrance(vignette, sc.VIBRANCE * strength)
            full, info = sc.render(base, faces, strength)
            factor = float(np.exp2(info["face_cut_ev"]))
            lines.append(f"CASE,{name},{base.shape[1]},{base.shape[0]},{strength:.17g},{factor:.17g}")
            rows = np.concatenate((base, faces[..., None], stage3, vignette, character, full), -1).reshape(-1, 16)
            lines += ["PIX," + ",".join(f"{float(v):.10g}" for v in row) for row in rows]
    return "\n".join(lines) + "\n"


def check_exports() -> None:
    # Fixed-golden boundaries are explicit for inputs, unbounded intermediates and final RGB.
    from export_android_orton import assert_regenerated_pixels
    if CONSTANTS.read_text(encoding="utf-8") != constants():
        raise AssertionError("Generated character constants differ from PC")
    expected, actual = fixture().splitlines(), gzip.decompress(FIXTURE.read_bytes()).decode("utf-8").splitlines()
    if len(expected) != len(actual):
        raise AssertionError("Character fixture shape changed")
    for line, (want, got) in enumerate(zip(expected, actual), 1):
        a, b = want.split(","), got.split(",")
        if a[0] == "PIX":
            if a[0] != b[0] or len(a) != len(b):
                raise AssertionError(f"Character layout differs at line {line}")
            values = np.asarray(b[1:], dtype=float)
            if not np.all(np.isfinite(values)):
                raise AssertionError(f"Character nonfinite values at line {line}")
            assert_regenerated_pixels(b[1:5], a[1:5], f"character inputs line {line}", atol=2e-6)
            np.testing.assert_allclose(np.asarray(b[5:14], float), np.asarray(a[5:14], float),
                                       atol=2e-5, rtol=2e-6, equal_nan=False, err_msg=f"character intermediates line {line}")
            assert_regenerated_pixels(b[14:], a[14:], f"character final RGB line {line}")
        elif a[0] == "CASE":
            if a[:5] != b[:5] or len(a) != len(b):
                raise AssertionError(f"Character metadata differs at line {line}")
            np.testing.assert_allclose(float(b[5]), float(a[5]), atol=2e-6, rtol=0)
        elif want != got:
            raise AssertionError(f"Character header differs at line {line}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        CONSTANTS.write_text(constants(), encoding="utf-8", newline="\n")
        FIXTURE.write_bytes(gzip.compress(fixture().encode("utf-8"), mtime=0))
    else:
        check_exports()
    print("Wrote synthetic character exports" if args.write else "Character exports match PC")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
